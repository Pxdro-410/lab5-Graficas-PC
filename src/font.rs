/// Dibuja un solo caracter en el framebuffer
pub fn draw_char(fb: &mut Framebuffer, x: usize, y: usize, c: char, color: u32) {
    let glyph = get_glyph(c);
    for col in 0..5 {
        let col_bits = glyph[col];
        for row in 0..7 {
            if (col_bits & (1 << row)) != 0 {
                let px = x + col;
                let py = y + row;
                if px < fb.width && py < fb.height {
                    let idx = py * fb.width + px;
                    fb.buffer[idx] = color;
                }
            }
        }
    }
}

/// Dibuja una cadena de texto en el framebuffer
pub fn draw_text(fb: &mut Framebuffer, mut x: usize, y: usize, text: &str, color: u32) {
    for c in text.chars() {
        if c == '\n' {
            continue;
        }
        draw_char(fb, x, y, c, color);
        x += 6; // 5 píxeles de ancho + 1 píxel de espaciado
    }
}

/// Dibuja un panel rectangular oscuro con borde para albergar texto del menú
pub fn draw_panel(
    fb: &mut Framebuffer,
    x: usize,
    y: usize,
    width: usize,
    height: usize,
    bg_color: u32,
    border_color: u32,
) {
    for py in y..(y + height).min(fb.height) {
        for px in x..(x + width).min(fb.width) {
            let is_border = py == y || py == y + height - 1 || px == x || px == x + width - 1;
            let idx = py * fb.width + px;
            if is_border {
                fb.buffer[idx] = border_color;
            } else {
                // Mezcla transparente con el fondo existente del 75%
                let orig = fb.buffer[idx];
                let or = (orig >> 16) & 0xFF;
                let og = (orig >> 8) & 0xFF;
                let ob = orig & 0xFF;

                let br = (bg_color >> 16) & 0xFF;
                let bg = (bg_color >> 8) & 0xFF;
                let bb = bg_color & 0xFF;

                let r = (br * 3 + or) / 4;
                let g = (bg * 3 + og) / 4;
                let b = (bb * 3 + ob) / 4;

                fb.buffer[idx] = (r << 16) | (g << 8) | b;
            }
        }
    }
}

